"""Encode the 15 actual After Hours studio PNGs, preserving their alpha channel.

Optional local tool dependency: Pillow. No files are downloaded or generated by AI.
The old render files are preserved; this writes only finish-pose.webp outputs.
"""
from pathlib import Path
from PIL import Image, ImageChops

root = Path(__file__).resolve().parents[1]
finishes = ('volt', 'ice', 'infrared')
poses = ('hero', 'side', 'knit', 'heel', 'sole')
names = [f'{finish}-{pose}' for finish in finishes for pose in poses]
source_dir = root / 'assets' / 'render-source'
destination_dir = root / 'public' / 'renders'
missing = [f'{name}.png' for name in names if not (source_dir / f'{name}.png').is_file()]
if missing:
    raise SystemExit('Export these studio PNGs first: ' + ', '.join(missing))

# Validate all inputs before replacing any output, so an incomplete export pass
# cannot silently leave a mixture of old and new finish variants.
for name in names:
    with Image.open(source_dir / f'{name}.png') as source:
        if source.size != (1200, 900) or 'A' not in source.getbands():
            raise SystemExit(f'{name}.png must be a transparent 1200 x 900 PNG.')

destination_dir.mkdir(parents=True, exist_ok=True)
total = 0
for name in names:
    destination = destination_dir / f'{name}.webp'
    with Image.open(source_dir / f'{name}.png') as source:
        rgba = source.convert('RGBA')
        rgba.save(destination, 'WEBP', quality=90, method=6, exact=True)
        with Image.open(destination) as decoded:
            if ImageChops.difference(rgba.getchannel('A'), decoded.convert('RGBA').getchannel('A')).getbbox():
                raise RuntimeError(f'{name}: exported alpha differs from its PNG source.')
    size = destination.stat().st_size
    total += size
    print(f'{name}.webp: {size} bytes; 1200 x 900; alpha preserved')
print(f'{len(names)} posters, {total} bytes total. Older assets preserved.')
